import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

// Disposable classroom keys. Private keys exist only while generating these fixtures.
const publisher = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
const second = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
const files = {
  'home-screen.txt': 'Welcome to the classroom launcher.',
  'login-panel.txt': 'Sign in to continue.',
  'news-feed.txt': 'Today: team presentation at 10:00.',
  'update-list.txt': 'Release 1.0.0 is ready.',
};
const changed = Object.fromEntries(
  Object.entries(files).map(([name, value]) => [name, value + ' [Classroom change]']),
);
const makeManifest = (resources, privateKey) => {
  const payload = JSON.stringify({
    release: '1.0.0',
    files: Object.entries(resources).map(([id, data]) => ({
      id,
      sha256: createHash('sha256').update(data, 'utf8').digest('hex'),
    })),
  });
  const signature = sign('sha256', Buffer.from(payload), {
    key: privateKey,
    dsaEncoding: 'ieee-p1363',
  }).toString('base64');
  return { payload, signature };
};
const proof = {
  publicKey: publisher.publicKey.export({ type: 'spki', format: 'der' }).toString('base64'),
  manifest: makeManifest(files, publisher.privateKey),
  untrustedManifest: makeManifest(changed, second.privateKey),
  files,
  changed,
};

await writeFile(new URL('../public/fixtures.js', import.meta.url),
  '// Generated by scripts/fixtures.mjs. Contains only public fixture data.\n' +
  'export const fixtures = ' + JSON.stringify(proof, null, 2) + ';\n');
