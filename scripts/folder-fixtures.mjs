import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { crc32 } from 'node:zlib';

const files = {
  'aegis-fix.min.js': '// COMP5578 classroom sample: launcher startup resource.\n',
  'images.7fec4c32.js': '// COMP5578 classroom sample: launcher image resource.\n',
  'FeedList.feb647c9.js': '// COMP5578 classroom sample: launcher news resource.\n',
  'vue-bucket.min.js': '// COMP5578 classroom sample: launcher interface resource.\n',
};
const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
const envelope = {
  payload: JSON.stringify({
    release: 'classroom-folder-1',
    files: Object.entries(files).map(([id, data]) => ({
      id, sha256: createHash('sha256').update(data).digest('hex'),
    })),
  }),
};
envelope.signature = sign('sha256', Buffer.from(envelope.payload), { key: privateKey, dsaEncoding: 'ieee-p1363' }).toString('base64');
const fixture = { publicKey: publicKey.export({ type: 'spki', format: 'der' }).toString('base64'), envelope };

// Store the exact signed bytes in a ZIP without requiring an archiving dependency.
const local = [];
const central = [];
let offset = 0;
for (const [id, text] of Object.entries(files)) {
  const name = Buffer.from('NIKKE-classroom-sources/' + id);
  const bytes = Buffer.from(text);
  const header = Buffer.alloc(30);
  header.writeUInt32LE(0x04034b50, 0);
  header.writeUInt16LE(20, 4);
  header.writeUInt16LE(33, 12); // Jan 1 1980, in DOS date format
  header.writeUInt32LE(crc32(bytes), 14);
  header.writeUInt32LE(bytes.length, 18);
  header.writeUInt32LE(bytes.length, 22);
  header.writeUInt16LE(name.length, 26);
  const entry = Buffer.alloc(46);
  entry.writeUInt32LE(0x02014b50, 0);
  entry.writeUInt16LE(20, 4);
  header.copy(entry, 6, 4, 30);
  entry.writeUInt32LE(offset, 42);
  local.push(header, name, bytes);
  central.push(entry, name);
  offset += header.length + name.length + bytes.length;
}
const directory = Buffer.concat(central);
const end = Buffer.alloc(22);
end.writeUInt32LE(0x06054b50, 0);
end.writeUInt16LE(central.length / 2, 8);
end.writeUInt16LE(central.length / 2, 10);
end.writeUInt32LE(directory.length, 12);
end.writeUInt32LE(offset, 16);
const base = new URL('../public/', import.meta.url);
await Promise.all([
  writeFile(new URL('nikke-source-samples.zip', base), Buffer.concat([...local, directory, end])),
  writeFile(new URL('folder-fixture.js', base),
    '// Generated by scripts/folder-fixtures.mjs from harmless classroom text.\n' +
    'export const folderFixture = ' + JSON.stringify(fixture, null, 2) + ';\n'),
]);
